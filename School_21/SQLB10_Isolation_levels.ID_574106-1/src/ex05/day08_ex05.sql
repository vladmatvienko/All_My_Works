-- Session #1
-- 1. Начало транзакции
BEGIN;

-- 2. Первое суммирование рейтингов
-- Фиксируем текущую сумму всех рейтингов.
-- Допустим, текущая сумма = 21.9 (зависит от данных в вашей БД)
SELECT SUM(rating) FROM pizzeria;

-- 3. Второе суммирование рейтингов (После INSERT и COMMIT в Session #2)
-- На уровне READ COMMITTED каждый оператор SELECT видит данные,
-- зафиксированные на момент начала этого оператора.
-- Поскольку Session #2 вставила новую строку и сделала COMMIT,
-- этот запрос увидит новую строку ("фантом").
SELECT SUM(rating) FROM pizzeria;
-- Ожидаемый вывод: Сумма увеличилась на 5 (например, стала 25.0).

-- 4. Завершение транзакции
COMMIT;

-- 5. Финальная проверка (после завершения транзакции)
SELECT SUM(rating) FROM pizzeria;
-- Ожидаемый вывод: Сумма равна 26.9 (как и во втором запросе).


-- Session #2

-- 1. Начало транзакции
BEGIN;

-- 2. Вставка новой пиццерии
-- Добавляем новую строку, которая станет "фантомом" для Session #1.
INSERT INTO pizzeria (id, name, rating) VALUES (10, 'Kazan Pizza', 5);

-- 3. Фиксация изменений
-- Делаем изменения видимыми для других транзакций.
COMMIT;

-- 4. Финальная проверка (после завершения всех транзакций)
SELECT SUM(rating) FROM pizzeria;
-- Ожидаемый вывод: Сумма равна 26.9.